#!/usr/bin/env python3
"""Build a small Bionic preload library with Clang13, without an NDK install.

The two link stubs only declare standard Bionic dependencies and never ship.
The resulting ELF has DT_NEEDED libc.so/libdl.so, resolved on the phone.
"""
import argparse
from pathlib import Path
import subprocess


def main():
    p = argparse.ArgumentParser()
    p.add_argument("out", type=Path)
    p.add_argument("kernel", type=Path)
    p.add_argument("--llvm", type=Path, default=Path("/usr/lib/llvm-13/bin"))
    a = p.parse_args()
    out = a.out / "adbroot-library"
    out.mkdir(parents=True, exist_ok=True)
    common = [str(a.llvm / "clang"), "--target=aarch64-linux-android31", "-fuse-ld=lld",
              "-shared", "-fPIC", "-nostdlib", "-Oz", "-fno-stack-protector",
              "-fno-builtin", "-fno-unwind-tables", "-fno-asynchronous-unwind-tables",
              "-Wl,-z,max-page-size=4096", "-Wl,--build-id=none"]
    for library, source in {
        "libdl.so": "void *dlsym(void *a,const char*b){return (void*)0;}\n",
        "libc.so": "int unsetenv(const char *name){return 0;}\n",
    }.items():
        stub = out / (library + ".c")
        stub.write_text(source)
        subprocess.run(common + ["-Wl,-soname," + library, str(stub),
                                  "-o", str(out / library)], check=True)
    result = out / "libcannon_adbroot.so"
    subprocess.run(common + ["-Wall", "-Wextra", "-Werror", "-fvisibility=hidden",
                              "-Wl,--no-undefined", "-Wl,-soname,libcannon_adbroot.so",
                              str(Path(__file__).with_name("adbroot.c")),
                              "-L" + str(out), "-ldl", "-lc", "-o", str(result)], check=True)
    blob = result.read_bytes()
    assert blob[:5] == b"\x7fELF\x02" and blob[18:20] == b"\xb7\x00"
    header = "/* Generated by cannon/build_adbroot.py; Bionic ELF, not the link stubs. */\n"
    header += "static const unsigned char cannon_adbroot_blob[] = {\n"
    for offset in range(0, len(blob), 16):
        header += "    " + ",".join(f"0x{x:02x}" for x in blob[offset:offset + 16]) + ",\n"
    header += "};\n"
    target = a.kernel / "kernel/cannon_adbroot_blob.h"
    if not target.exists() or target.read_text() != header:
        target.write_text(header)
    print(f"Bionic adbroot ELF: {result}, {len(blob)} bytes; embedded header {target}")


if __name__ == "__main__":
    main()
