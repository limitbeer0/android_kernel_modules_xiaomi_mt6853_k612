#!/usr/bin/env python3
"""Generate the cannon-only 4.14 DT clock ID -> 6.12 provider ID tables."""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OLD = ROOT.parent / "MT6853T_xiaomi_custom_kernel/include/dt-bindings/clock/mt6853-clk.h"
NEW = ROOT / "kernel_device_modules-6.12/include/dt-bindings/clock/mt6853-clk.h"
OUT = ROOT / "kernel_device_modules-6.12/drivers/clk/mediatek/clk-mt6853-cannon-ids.h"
# These renamed gates have the same register bank, bit and parent in both trees.
ALIASES = {
    "CLK_IFRAO_PMIC_TMR": "CLK_IFRAO_PMIC_TMR_SET",
    "CLK_IFRAO_PMIC_AP": "CLK_IFRAO_PMIC_AP_SET",
    "CLK_IFRAO_GCE_26M": "CLK_IFRAO_GCE_26M_SET",
    "CLK_IFRAO_AES": "CLK_IFRAO_UFS_AES",
    "CLK_IFRAO_PERU_BUS_DCM_133M": "CLK_IFRAO_PERI_BUS_DCM_133M",
    "CLK_IFRAO_PERU_BUS_DCM_66M": "CLK_IFRAO_PERI_BUS_DCM_66M",
}

def defines(p):
    return {k: int(v) for k, v in re.findall(r"#define\s+(CLK_\w+)\s+(\d+)", p.read_text())}

def generate():
    old, new = defines(OLD), defines(NEW)
    out = ["/* SPDX-License-Identifier: GPL-2.0 */",
           "/* Generated by cannon/gen_clock_map.py; legacy DT IDs are not 6.12 IDs.",
           " * Values are new ID + 1; zero rejects a missing legacy clock.",
           " * Keep 6.12 internal IDs unchanged, including its registration paths.",
           " */", ""]
    for prefix, name in (("CLK_TOP_", "top"), ("CLK_IFRAO_", "infra")):
        out.append(f"static const u16 cannon_{name}_ids[{old[prefix + 'NR_CLK']}] = {{")
        for key, value in old.items():
            if not key.startswith(prefix) or key.endswith("NR_CLK"):
                continue
            target = ALIASES.get(key, key)
            if target in new:
                out.append(f"\t[{value}] = {target} + 1, /* {key} */")
        out += ["};", ""]
    # These are the four critical consumers checked against the source headers.
    assert old["CLK_TOP_PWRAP_ULPOSC_SEL"] == 185
    assert new["CLK_TOP_PWRAP_ULPOSC_SEL"] == 211
    assert old["CLK_IFRAO_UFS"] == 76 and new["CLK_IFRAO_UFS"] == 60
    OUT.write_text("\n".join(out))
    print(OUT)

if __name__ == "__main__":
    generate()
